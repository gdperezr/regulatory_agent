"""Cria as tabelas do Meu Financeiro se ainda não existirem."""


class EsquemaBanco:
    """Pessoas, cartões, compras e parcelas da fatura no PostgreSQL."""

    def criar(self, conn) -> None:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              name TEXT NOT NULL,
              login TEXT NOT NULL UNIQUE,
              password_hash TEXT NOT NULL
            )
            """
        )
        conn.execute(
            """
            DO $$
            BEGIN
              IF EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'email'
              ) THEN
                ALTER TABLE users RENAME COLUMN email TO login;
              END IF;
            END $$;
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS cards (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              owner_id INTEGER REFERENCES users (id),
              name TEXT NOT NULL,
              credit_limit_cents INTEGER NOT NULL CHECK (credit_limit_cents >= 0),
              closing_day INTEGER NOT NULL CHECK (closing_day BETWEEN 1 AND 31),
              due_day INTEGER NOT NULL CHECK (due_day BETWEEN 1 AND 31)
            )
            """
        )
        conn.execute("ALTER TABLE cards ADD COLUMN IF NOT EXISTS owner_id INTEGER REFERENCES users (id)")
        conn.execute("ALTER TABLE cards DROP CONSTRAINT IF EXISTS cards_name_key")
        conn.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS cards_owner_name_uidx ON cards (owner_id, name)"
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS purchases (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              card_id INTEGER NOT NULL REFERENCES cards (id),
              description TEXT NOT NULL,
              purchase_date TEXT NOT NULL,
              total_cents INTEGER NOT NULL CHECK (total_cents > 0),
              installments INTEGER NOT NULL CHECK (installments BETWEEN 1 AND 120)
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS invoice_items (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              purchase_id INTEGER NOT NULL REFERENCES purchases (id) ON DELETE CASCADE,
              installment_number INTEGER NOT NULL,
              invoice_month TEXT NOT NULL,
              amount_cents INTEGER NOT NULL CHECK (amount_cents >= 0),
              UNIQUE (purchase_id, installment_number)
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS fixed_costs (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              owner_id INTEGER NOT NULL REFERENCES users (id),
              description TEXT NOT NULL,
              amount_cents INTEGER NOT NULL CHECK (amount_cents > 0)
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS incomes (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              owner_id INTEGER NOT NULL REFERENCES users (id),
              description TEXT NOT NULL,
              amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
              income_month TEXT NOT NULL
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS month_closings (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              owner_id INTEGER NOT NULL REFERENCES users (id),
              closing_month TEXT NOT NULL,
              income_cents INTEGER NOT NULL,
              expense_cents INTEGER NOT NULL,
              balance_cents INTEGER NOT NULL,
              closed_at TEXT NOT NULL,
              UNIQUE (owner_id, closing_month)
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS remembered_sessions (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
              token_hash TEXT NOT NULL UNIQUE,
              expires_at TIMESTAMPTZ NOT NULL
            )
            """
        )
